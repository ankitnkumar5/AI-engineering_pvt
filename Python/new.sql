#--------------------Beginner SQL

Database Basics: Relational model, tables, rows, columns, primary & foreign keys

Querying Data: SELECT, DISTINCT, column aliasing (AS)

Filtering: WHERE, logical operators (AND, OR, NOT), IN, BETWEEN, LIKE, IS NULL

Sorting & Limiting: ORDER BY, LIMIT / TOP / FETCH FIRST

Aggregation: COUNT, SUM, AVG, MIN, MAX, GROUP BY, HAVING

Basic Joins: INNER JOIN, LEFT JOIN, RIGHT JOIN

Data Manipulation (DML): INSERT, UPDATE, DELETE

Data Definition (DDL): CREATE TABLE, ALTER TABLE, DROP TABLE, basic constraints (NOT NULL, UNIQUE, CHECK)

#------------------------Intermediate SQL

Advanced Joins: FULL OUTER JOIN, CROSS JOIN, SELF JOIN

Set Operators: UNION, UNION ALL, INTERSECT, EXCEPT / MINUS

Conditional Logic: CASE WHEN ... THEN ... ELSE ... END, COALESCE, NULLIF

Subqueries: Scalar subqueries, correlated subqueries, EXISTS vs. IN

Common Table Expressions (CTEs): Standard WITH clause for readability and modularity

Views: Creating, updating, and querying views

Built-in Functions: String operations, date/time manipulation, numeric functions, type casting (CAST, CONVERT)

Transactions & Data Control: COMMIT, ROLLBACK, SAVEPOINT, ACID properties, basic GRANT / REVOKE

#-------------------------------Expert SQL

Window Functions: ROW_NUMBER(), RANK(), DENSE_RANK(), LEAD(), LAG(), frame specifications (ROWS/RANGE BETWEEN)

Advanced CTEs: Recursive queries for hierarchical and graph data structures

Indexing & Performance Tuning: B-tree vs. Hash indexes, composite indexes, query execution plans (EXPLAIN), index scans vs. seeks

Advanced Aggregations: GROUPING SETS, CUBE, ROLLUP

Database Design & Optimization: Normalization (1NF to 3NF/BCNF), denormalization strategies, partitioning (range, list, hash)

Programmability: Stored procedures, user-defined functions (UDFs), triggers, dynamic SQL

Concurrency & Locking: Isolation levels (READ COMMITTED, SERIALIZABLE), deadlocks, optimistic vs. pessimistic locking

JSON & Semi-Structured Data: Querying JSON paths, arrays, and unstructured types directly within SQL